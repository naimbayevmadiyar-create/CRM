-- Своя дата у счёта.
--
-- Дата в бланке не всегда совпадает с днём, когда его завели в системе:
-- ремонт был на прошлой неделе, а счёт просят сегодня — и датировать его
-- надо днём работ. У заявки для этого уже есть contract_date, счёту нужна
-- своя: он живёт отдельно от заявки.

alter table invoices
  add column issued_on date;

comment on column invoices.issued_on is
  'Дата в бланке счёта. Пусто — берётся день создания счёта';

notify pgrst, 'reload schema';
